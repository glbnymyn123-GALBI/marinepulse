// Rebuilds data/sightings.js from the CSV so index.html works from file:// (no server).
// Run after editing the sheet: node tools/embed_data.js [path/to.csv]
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = process.argv[2] || path.join(root, 'data/marine_mammal_sightings_2026.csv');
const csv = fs.readFileSync(src, 'utf8');
const out = `/* Generated by tools/embed_data.js from ${path.basename(src)}. Do not edit by hand. */\n` +
  `window.MP_EMBEDDED = { name: ${JSON.stringify(path.basename(src))}, csv: ${JSON.stringify(csv)} };\n`;
fs.writeFileSync(path.join(root, 'data/sightings.js'), out);
console.log(`Wrote data/sightings.js (${(out.length / 1024).toFixed(1)} KB)`);
